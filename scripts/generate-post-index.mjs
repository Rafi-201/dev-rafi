/**
 * Writes src/data/posts.ts from content/posts/*.md so the React app can list
 * posts without needing a markdown loader in the client bundle.
 *
 * Runs automatically before `npm run build` (and before `npm run dev`).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { publishedPosts, REVEAL_THRESHOLD, ROOT } from "./lib/posts.mjs";

const posts = publishedPosts().map(({ slug, title, description, date, tags, readingTime }) => ({
  slug,
  title,
  description,
  date,
  tags,
  readingTime,
}));

const file = `// Generated by scripts/generate-post-index.mjs — do not edit by hand.
// Add or edit posts in content/posts/*.md and rebuild.

export type PostMeta = {
  slug: string;
  title: string;
  description: string;
  date: string;
  tags: string[];
  readingTime: number;
};

/**
 * The Writing section and its nav link stay hidden until this many posts are
 * published. A visibly empty blog is worse than no blog.
 */
export const REVEAL_THRESHOLD = ${REVEAL_THRESHOLD};

export const posts: PostMeta[] = ${JSON.stringify(posts, null, 2)};

export const blogIsLive = posts.length >= REVEAL_THRESHOLD;
`;

const outDir = join(ROOT, "src", "data");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "posts.ts"), file, "utf8");

console.log(
  `[blog] indexed ${posts.length} published post(s); ` +
    `blog is ${posts.length >= REVEAL_THRESHOLD ? "LIVE" : `hidden until ${REVEAL_THRESHOLD}`}`
);
